_FONTS = {
    "tiny": (_GLYPHS_3X5, 3, 5, 1),
    "medium": (_GLYPHS_5X7, 5, 7, 1),
    "large": (_GLYPHS_5X7, 5, 7, 2),   # 10×14
    "giant": (_GLYPHS_5X7, 5, 7, 3),   # 15×21
}


def font_size(name):
    """Return ``(glyph_w, glyph_h, scale)`` for a font size name."""
    glyphs, gw, gh, scale = _FONTS[name]
    return gw * scale, gh * scale


def measure(text, name):
    """Return the pixel width/height of ``text`` rendered with ``name``."""
    glyphs, gw, gh, scale = _FONTS[name]
    step = (gw + 1) * scale
    width = max(0, len(text) * step - scale)
    return width, gh * scale


def text_bitmap(text, name):
    """Render ``text`` to a boolean HxW numpy matrix (True = pixel on)."""
    glyphs, gw, gh, scale = _FONTS[name]
    text = (text or "").upper()
    step = (gw + 1) * scale
    width = max(1, len(text) * step - scale)
    height = gh * scale
    grid = np.zeros((height, width), dtype=bool)

    for index, char in enumerate(text):
        bitmap = glyphs.get(char, glyphs[" "])
        ox = index * step
        for row, line in enumerate(bitmap):
            for col, value in enumerate(line):
                if value != "#":
                    continue
                y0 = row * scale
                x0 = ox + col * scale
                grid[y0:y0 + scale, x0:x0 + scale] = True
    return grid
